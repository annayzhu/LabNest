import {openQpcrFromSlash} from './qpcr-browser-helpers.mjs';
import {chromium} from 'playwright';
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const base=process.env.BASE_URL ?? 'http://localhost:3002';
const ids=JSON.parse(await readFile('/private/tmp/qpcr-fixtures.json','utf8'));
const browser=await chromium.launch();const page=await browser.newPage({viewport:{width:1440,height:900}});
page.on('pageerror',e=>console.log('PAGEERROR',e.stack));page.on('response',async r=>{if(r.url().includes('qpcr-workflow')&&r.status()>=400)console.log('APIERROR',await r.text());});
await page.goto(`${base}/results/new?experiment=${ids.experimentId}&manual=1`);
await page.getByRole('textbox',{name:'Result title',exact:true}).fill('qPCR 合成验收 · 45 类别 · 草稿恢复');
await page.locator('.tiptap p').first().fill('合成验收观察：保留手写正文。');
await openQpcrFromSlash(page,'qPCR 分析');
const frame=page.frameLocator('iframe[title="qPCR 分析"]');
await frame.getByRole('button',{name:'EN',exact:true}).click();
await frame.getByRole('radio',{name:/Start from ΔΔCq/}).click();
const lines=['Sample\tAssay\tAssay Type\tReplicate\tDelta Delta Cq'];
for(let sample=1;sample<=45;sample++)for(let rep=1;rep<=3;rep++)lines.push([`Sample-${sample}-长名称-所有字符均须保留实验处理分组`,'GENE','Target',rep,(sample%5)+rep*0.1].join('\t'));
await frame.locator('input[type="file"]').first().setInputFiles({name:'synthetic-45.tsv',mimeType:'text/tab-separated-values',buffer:Buffer.from(lines.join('\n'))});
await frame.getByRole('button',{name:'Confirm incomplete',exact:true}).click();
await frame.locator('.readiness-actions button').click();
await frame.locator('.workspace-tabs').getByRole('button',{name:/Results & figures/}).click();
await frame.locator('.workflow-chart:not([hidden]) svg').first().waitFor();
assert.equal(await frame.locator('svg text[aria-label^="Sample-"]').count(),45);
const geometry=await frame.locator('.workflow-chart:not([hidden]) svg').first().evaluate(svg=>({width:svg.getBoundingClientRect().width,minFont:Math.min(...Array.from(svg.querySelectorAll('text')).map(t=>Number(t.getAttribute('font-size'))||12))*svg.getBoundingClientRect().width/svg.viewBox.baseVal.width}));
assert.ok(geometry.minFont>=12,JSON.stringify(geometry));
await page.getByRole('button',{name:'返回记录',exact:true}).click();
await page.locator('dialog').waitFor({state:'detached'});
await page.reload();
await page.waitForFunction(()=>document.querySelector('[aria-label="Result title"]')?.value.includes('45'));
assert.equal(await page.getByRole('textbox',{name:'Result title',exact:true}).inputValue(),'qPCR 合成验收 · 45 类别 · 草稿恢复');
assert.match(await page.locator('.tiptap').innerText(),/保留手写正文/);
await openQpcrFromSlash(page,'qPCR 分析');
await frame.locator('.workflow-chart:not([hidden]) svg').first().waitFor();
assert.equal(await frame.locator('svg text[aria-label^="Sample-"]').count(),45);
await page.getByRole('button',{name:'插入结果',exact:true}).click();
await page.locator('dialog').waitFor({state:'detached'});
assert.equal(await page.locator('.qpcr-output img').count(),8);
assert.equal(await page.locator('.qpcr-output tbody tr').count(),45);
await page.reload();
await page.locator('.qpcr-output img').first().waitFor();
assert.equal(await page.locator('.qpcr-output img').count(),8);
await page.getByRole('button',{name:/Save Result|保存结果|Save changes/i}).click();
await page.waitForURL(url=>/^\/results\/c[a-z0-9]+$/.test(url.pathname));
await writeFile('/private/tmp/qpcr-draft-result-url.txt',page.url());
assert.equal(await page.locator('.qpcr-output img').count(),8);
console.log('PASS 45 categories, 8 facets, title/text/session recovery, final save',page.url(),geometry);
await browser.close();
