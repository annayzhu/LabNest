import {openQpcrFromSlash} from './qpcr-browser-helpers.mjs';
import {chromium} from 'playwright';
import {readFile} from 'node:fs/promises';import assert from 'node:assert/strict';
const ids=JSON.parse(await readFile('/private/tmp/qpcr-fixtures.json','utf8'));
const browser=await chromium.launch();const context=await browser.newContext();const page=await context.newPage();
page.on('pageerror',e=>console.log('PAGEERROR',e.message));
const target=`http://localhost:3002/results/new?experiment=${ids.experimentId}&manual=1`;
await page.goto(target);await page.waitForFunction(()=>document.querySelector('[name=qpcrDraftId]')?.value);
const first=await page.locator('[name=qpcrDraftId]').inputValue();
const secondPage=await context.newPage();await secondPage.goto(target);await secondPage.waitForFunction(()=>document.querySelector('[name=qpcrDraftId]')?.value);
assert.notEqual(first,await secondPage.locator('[name=qpcrDraftId]').inputValue());await secondPage.close();
await page.goto('http://localhost:3002/research-plans/new');
await page.getByRole('textbox',{name:'Research Plan title',exact:true}).fill('合成草稿清理验收');
await page.getByRole('tab',{name:/Metadata|属性|信息/}).click();
await page.locator('select[name=projectId]').selectOption(ids.projectId);
await page.getByText('Code, status and tags',{exact:true}).click();
await page.locator('[name=codeSuffix]').fill(String(Date.now()).slice(-9));
await page.getByRole('tab',{name:'Document',exact:true}).click();
await page.locator('.tiptap p').first().fill('这段文字只属于当前研究计划');
await page.waitForResponse(r=>r.url().includes('/api/qpcr-workflow') && r.request().method()==='POST' && r.status()===200);
await page.reload();
await page.waitForFunction(()=>document.querySelector('[aria-label="Research Plan title"]')?.value==='合成草稿清理验收');
assert.equal(await page.locator('select[name=projectId]').inputValue(),ids.projectId);
await page.getByRole('button',{name:/Save Research Plan/}).click();
await page.waitForURL(url=>/^\/research-plans\/c[a-z0-9]+$/.test(url.pathname));
await page.goto('http://localhost:3002/research-plans/new');
assert.equal(await page.getByRole('textbox',{name:'Research Plan title',exact:true}).inputValue(),'');
assert.doesNotMatch(await page.locator('.tiptap').innerText(),/这段文字只属于当前研究计划/);
await page.goto(`http://localhost:3002/experiments/${ids.experimentId}/edit`);
await page.getByRole('button',{name:'编辑布局',exact:true}).first().click();
const frame=page.frameLocator('iframe[title="qPCR 板布局"]');
await frame.locator('.sample-name-input').first().fill('Synthetic_Draft_A');
await page.getByRole('button',{name:'返回记录',exact:true}).click();await page.locator('dialog').waitFor({state:'detached'});
await openQpcrFromSlash(page,'qPCR 板布局');
await frame.getByRole('button',{name:'载入示例',exact:true}).click();await frame.getByRole('button',{name:'生成布局',exact:true}).click();
await page.getByRole('button',{name:'保存到计划',exact:true}).click();await page.locator('dialog').waitFor({state:'detached'});
await page.getByRole('button',{name:'编辑布局',exact:true}).first().click();
await page.waitForFunction(()=>document.querySelector('iframe')?.contentDocument?.querySelector('.sample-name-input')?.value==='Synthetic_Draft_A');
assert.equal(await frame.locator('.sample-name-input').first().inputValue(),'Synthetic_Draft_A');
console.log('PASS distinct new drafts, finalized plan cleanup, independent pending outputs');await browser.close();
