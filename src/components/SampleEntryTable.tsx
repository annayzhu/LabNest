"use client";

import { memo, useCallback, useMemo, useState, type ClipboardEvent } from "react";
import { useRouter } from "next/navigation";
import { ClipboardPaste, FileUp, ListPlus, MapPin, Plus, Table2, Trash2 } from "lucide-react";
import { checkSampleBatch, saveSampleBatch, type SampleBatchResult } from "@/app/samples/actions";
import { useI18n } from "@/components/I18nProvider";
import { formInlineInputClass, formInputClass } from "@/components/forms";
import { Button } from "@/components/ui/Button";
import { cn } from "@/lib/cn";
import { parseSpreadsheetClipboard } from "@/lib/result-dataset-paste";
import {
  biosafetyLevels, freePositions, mapSampleHeaders, matchKey, MAX_SAMPLE_BATCH, nameSeries, normalizePosition, sampleColumns, sampleRowsFromCells, sampleTypeNamed,
  type BoxGeometry, type SampleRowInput, type SampleTypeRef,
} from "@/lib/samples";

export type SampleEntryRow = SampleRowInput & { key: string };
type Location = { id: string; label: string; name: string; geometry: BoxGeometry | null };
type ResultTable = { key: string; label: string; headers: string[]; rows: string[][] };
type Imported = { headers: string[]; rows: string[][]; columns: string[] };

const cellClass = cn(formInlineInputClass, "h-8 w-full min-w-0 text-sm");
let keySeed = 0;
const newKey = () => `row-${Date.now().toString(36)}-${(keySeed += 1)}`;
const editable = ["name", "code", "typeId", "origin", "parentCode", "locationId", "position", "amount", "amountUnit", "concentration", "concentrationUnit", "collectedAt", "biosafetyLevel", "notes"] as const;
type Column = (typeof editable)[number];

/**
 * The one table for new samples (S8): typed row by row, pasted from Excel, imported from a file or generated by a rule,
 * placed into a box's free positions, checked against the database and saved as one batch. It also registers an
 * experiment's outputs (S11) and aliquots of a sample (S9), with rows prefilled.
 */
export function SampleEntryTable({ types, locations, occupied, projects, initialRows, defaultTypeId, experiment, aliquot, resultTables = [] }: {
  types: SampleTypeRef[];
  locations: Location[];
  /** Positions held in each box with a grid. */
  occupied: Record<string, string[]>;
  projects: Array<{ id: string; name: string }>;
  initialRows: SampleRowInput[];
  defaultTypeId?: string;
  experiment?: { id: string; runCode: string; title: string; projectId: string | null };
  aliquot?: { id: string; code: string; name: string; amount: number | null; amountUnit: string | null };
  resultTables?: ResultTable[];
}) {
  const { t, locale } = useI18n();
  const router = useRouter();
  const [rows, setRows] = useState<SampleEntryRow[]>(() => (initialRows.length ? initialRows : [{}]).map((row) => ({ typeId: defaultTypeId, ...row, key: newKey() })));
  const [batchType, setBatchType] = useState(defaultTypeId ?? types[0]?.id ?? "");
  const [projectId, setProjectId] = useState(experiment?.projectId ?? "");
  const [problems, setProblems] = useState<Map<number, string[]>>(new Map());
  const [message, setMessage] = useState<{ tone: "error" | "ok"; text: string } | null>(null);
  const [busy, setBusy] = useState(false);
  const [panel, setPanel] = useState<"paste" | "generate" | "place" | "result" | null>(null);
  const [imported, setImported] = useState<Imported | null>(null);
  const [pasteText, setPasteText] = useState("");
  const [generate, setGenerate] = useState({ count: "8", prefix: "", start: "1", width: "2", suffix: "" });
  const [place, setPlace] = useState({ locationId: locations.find((location) => location.geometry)?.id ?? "", start: "A1", onlyEmpty: true });
  const [resultKey, setResultKey] = useState(resultTables[0]?.key ?? "");
  const [aliquotAdjust, setAliquotAdjust] = useState({ subtract: true, depleted: false });

  const typeById = useMemo(() => new Map(types.map((type) => [type.id, type])), [types]);
  const fieldType = typeById.get(batchType);
  const lookup = useMemo(() => ({
    typeId: (text: string) => sampleTypeNamed(types, text)?.id,
    locationId: (text: string) => {
      const exact = locations.find((location) => matchKey(location.label) === matchKey(text));
      const named = locations.filter((location) => matchKey(location.name) === matchKey(text));
      return exact?.id ?? (named.length === 1 ? named[0].id : undefined);
    },
  }), [types, locations]);

  const update = useCallback((key: string, patch: Partial<SampleRowInput>) => setRows((current) => current.map((row) => (row.key === key ? { ...row, ...patch } : row))), []);
  const remove = useCallback((key: string) => setRows((current) => (current.length > 1 ? current.filter((row) => row.key !== key) : [{ key: newKey(), typeId: batchType }])), [batchType]);
  const append = (added: SampleRowInput[], replace = false) => {
    setRows((current) => {
      const kept = replace ? [] : current.filter((row) => editable.some((column) => row[column]?.trim() && column !== "typeId") || Object.values(row.fields ?? {}).some((value) => value.trim()));
      const next = [...kept, ...added.map((row) => ({ typeId: batchType, ...row, key: newKey() }))];
      return next.length ? next.slice(0, MAX_SAMPLE_BATCH) : [{ key: newKey(), typeId: batchType }];
    });
    setProblems(new Map());
  };

  function readTable(text: string, delimiter = "\t") {
    const cells = parseSpreadsheetClipboard(text, delimiter).filter((row) => row.some((cell) => cell.trim()));
    if (!cells.length) return;
    const columns = mapSampleHeaders(cells[0], fieldType?.fields);
    // A first row that names no column is data: map by position over the visible columns.
    if (columns.every((column) => !column)) setImported({ headers: cells[0].map((_, index) => `${t("Column")} ${index + 1}`), rows: cells, columns: cells[0].map((_, index) => ["name", "code", "type", "origin", "parent", "box", "position", "amount", "amountUnit", "concentration", "concentrationUnit", "collectedAt", "biosafetyLevel", "notes"][index] ?? "") });
    else setImported({ headers: cells[0], rows: cells.slice(1), columns });
  }

  async function readFile(file: File) {
    setMessage(null);
    try {
      if (file.size > 10 * 1024 * 1024) throw new Error("The file is over 10 MB.");
      if (/\.xlsx$/i.test(file.name)) {
        const sheet = (await (await import("read-excel-file/browser")).readSheet(file)).map((row) => row.map((value) => (value instanceof Date ? value.toISOString().slice(0, 10) : value == null ? "" : String(value))));
        readTable(sheet.map((row) => row.join("\t")).join("\n"));
      } else readTable(await file.text(), /\.(tsv|txt)$/i.test(file.name) ? "\t" : ",");
      setPanel("paste");
    } catch (error) {
      setMessage({ tone: "error", text: error instanceof Error ? error.message : "The file could not be read." });
    }
  }

  /** A block pasted into a cell fills the table from that cell on, like a spreadsheet. */
  const pasteIntoCell = useCallback((event: ClipboardEvent<HTMLInputElement | HTMLSelectElement>, rowKey: string, column: Column) => {
    const text = event.clipboardData.getData("text/plain");
    if (!/[\t\n]/.test(text.replace(/\n$/, ""))) return;
    event.preventDefault();
    const cells = parseSpreadsheetClipboard(text.replace(/\r?\n$/, ""), "\t");
    const first = editable.indexOf(column);
    setRows((current) => {
      const next = [...current];
      let at = next.findIndex((row) => row.key === rowKey);
      for (const line of cells) {
        if (at >= MAX_SAMPLE_BATCH) break;
        if (at >= next.length) next.push({ key: newKey(), typeId: batchType });
        const patch: Partial<SampleRowInput> = {};
        line.forEach((value, offset) => {
          const target = editable[first + offset];
          if (!target) return;
          if (target === "typeId") patch.typeId = lookup.typeId(value) ?? (value.trim() ? `unknown:${value.trim()}` : next[at].typeId);
          else if (target === "locationId") patch.locationId = lookup.locationId(value) ?? (value.trim() ? `unknown:${value.trim()}` : undefined);
          else patch[target] = value.trim();
        });
        next[at] = { ...next[at], ...patch };
        at += 1;
      }
      return next;
    });
  }, [batchType, lookup]);

  function generateRows() {
    const count = Math.min(MAX_SAMPLE_BATCH, Math.max(1, Number(generate.count) || 0));
    const start = Number(generate.start) || 1, width = Math.max(0, Math.min(6, Number(generate.width) || 0));
    append(nameSeries({ prefix: generate.prefix, start, width, count, suffix: generate.suffix }).map((name) => ({ name })));
    setPanel(null);
  }

  function placeRows() {
    const box = locations.find((location) => location.id === place.locationId);
    if (!box) return;
    const others = rows.filter((row) => row.locationId === box.id && row.position).map((row) => normalizePosition(row.position));
    const targets = rows.filter((row) => !place.onlyEmpty || !row.position?.trim());
    if (!box.geometry) { setRows((current) => current.map((row) => (targets.includes(row) ? { ...row, locationId: box.id } : row))); setPanel(null); return; }
    const taken = [...(occupied[box.id] ?? []), ...(place.onlyEmpty ? others : [])];
    const free = freePositions(box.geometry, taken, place.start);
    if (free.length < targets.length) { setMessage({ tone: "error", text: t(`${box.label} has ${free.length} free positions from ${normalizePosition(place.start) || "A1"}; ${targets.length} are needed.`) }); return; }
    const assigned = new Map(targets.map((row, index) => [row.key, free[index]]));
    setRows((current) => current.map((row) => (assigned.has(row.key) ? { ...row, locationId: box.id, position: assigned.get(row.key) } : row)));
    setMessage(null);
    setPanel(null);
  }

  /** Concentration, volume and place from the experiment's per-sample result table (S11), matched by name, else by order. */
  function fillFromResult() {
    const table = resultTables.find((candidate) => candidate.key === resultKey);
    if (!table) return;
    const columns = mapSampleHeaders(table.headers, fieldType?.fields);
    const filled = sampleRowsFromCells(table.rows, columns, lookup);
    const byName = new Map(filled.flatMap((row) => (row.name ? [[matchKey(row.name), row] as const] : [])));
    setRows((current) => current.map((row, index) => {
      const source = (row.name && byName.get(matchKey(row.name))) || (!byName.size ? filled[index] : undefined);
      if (!source) return row;
      const { name, typeId: _type, ...values } = source;
      void _type;
      return { ...row, ...Object.fromEntries(Object.entries(values).filter(([, value]) => value !== undefined && value !== "")), name: row.name || name, fields: { ...row.fields, ...source.fields } };
    }));
    setPanel(null);
  }

  // Empty rows are left out of the batch; problems come back by batch row and are shown on the table's row.
  const filled = rows.flatMap((row, index) => (editable.some((column) => column !== "typeId" && row[column]?.trim()) || Object.values(row.fields ?? {}).some((value) => value.trim()) ? [index] : []));
  const payload = () => ({
    rows: filled.map((index) => { const { key: _key, ...row } = rows[index]; void _key; return { ...row, typeId: row.typeId || batchType }; }),
    projectId: projectId || undefined,
    experimentId: experiment?.id,
    ...(aliquot ? { aliquotOf: { sampleId: aliquot.id, ...aliquotAdjust } } : {}),
  });

  function show(result: SampleBatchResult, saved: boolean) {
    const map = new Map((result.problems ?? []).map((row) => [filled[row.index] ?? row.index, row.problems]));
    setProblems(map);
    if (result.error && !map.size) setMessage({ tone: "error", text: result.error });
    else if (map.size) setMessage({ tone: "error", text: t(`${map.size} rows need attention.`) });
    else if (!saved) setMessage({ tone: "ok", text: t(`All ${result.count ?? 0} rows can be saved.`) });
  }

  async function check() {
    setBusy(true);
    try { show(await checkSampleBatch(payload()), false); } finally { setBusy(false); }
  }

  async function save() {
    setBusy(true);
    try {
      const result = await saveSampleBatch(payload());
      if (result.href) { router.push(result.href); router.refresh(); return; }
      show(result, true);
    } finally { setBusy(false); }
  }

  const filledRows = filled.length;
  const colon = locale === "zh" ? "：" : ": ";
  return (
    <div className="space-y-3">
      {experiment ? <p className="rounded-[var(--ln-radius-panel)] border border-hairline bg-sage-surface px-3 py-2 text-sm text-moss"><span>Outputs of</span> <strong className="record-identifier">{experiment.runCode}</strong> · {experiment.title}</p> : null}
      {aliquot ? (
        <div className="flex flex-wrap items-center gap-x-4 gap-y-2 rounded-[var(--ln-radius-panel)] border border-hairline bg-sage-surface px-3 py-2 text-sm text-moss">
          <span><span>Aliquots of</span> <strong className="record-identifier">{aliquot.code}</strong> · {aliquot.name}</span>
          {aliquot.amount !== null ? <label className="inline-flex items-center gap-2"><input type="checkbox" checked={aliquotAdjust.subtract} onChange={(event) => setAliquotAdjust({ ...aliquotAdjust, subtract: event.target.checked })} />Subtract what is split off from the parent ({aliquot.amount} {aliquot.amountUnit})</label> : null}
          <label className="inline-flex items-center gap-2"><input type="checkbox" checked={aliquotAdjust.depleted} onChange={(event) => setAliquotAdjust({ ...aliquotAdjust, depleted: event.target.checked })} />Mark the parent as used up</label>
        </div>
      ) : null}

      <div className="flex flex-wrap items-end gap-3 border-y border-hairline bg-surface px-3 py-3">
        <label className="text-sm"><span className="mb-1 block text-xs font-medium text-muted">Type for new rows</span>
          <select value={batchType} onChange={(event) => { const next = event.target.value; setRows((current) => current.map((row) => (!row.typeId || row.typeId === batchType ? { ...row, typeId: next } : row))); setBatchType(next); }} className={cn(formInputClass, "h-9 min-w-40")}>
            {types.map((type) => <option key={type.id} value={type.id}>{type.label}</option>)}
          </select>
        </label>
        <label className="text-sm"><span className="mb-1 block text-xs font-medium text-muted">Project</span>
          <select value={projectId} onChange={(event) => setProjectId(event.target.value)} className={cn(formInputClass, "h-9 min-w-40")}>
            <option value="">No project</option>
            {projects.map((project) => <option key={project.id} value={project.id}>{project.name}</option>)}
          </select>
        </label>
        <div className="ml-auto flex flex-wrap gap-1.5">
          <Button type="button" size="sm" variant="ghost" onClick={() => append([{}])}><Plus className="h-3.5 w-3.5" aria-hidden />Add row</Button>
          <Button type="button" size="sm" variant="ghost" onClick={() => setPanel(panel === "generate" ? null : "generate")}><ListPlus className="h-3.5 w-3.5" aria-hidden />Generate rows…</Button>
          <Button type="button" size="sm" variant="ghost" onClick={() => setPanel(panel === "paste" ? null : "paste")}><ClipboardPaste className="h-3.5 w-3.5" aria-hidden />Paste from Excel…</Button>
          <label className="inline-flex"><span className="sr-only">Import a file</span><input type="file" accept=".csv,.tsv,.txt,.xlsx" className="sr-only" onChange={(event) => { const file = event.target.files?.[0]; if (file) void readFile(file); event.target.value = ""; }} /><span className="focus-ring inline-flex h-8 cursor-pointer items-center gap-1.5 rounded-[var(--ln-radius-control-sm)] px-2.5 text-sm font-medium text-graphite hover:bg-warm hover:text-ink"><FileUp className="h-3.5 w-3.5" aria-hidden />Import a file…</span></label>
          <Button type="button" size="sm" variant="ghost" onClick={() => setPanel(panel === "place" ? null : "place")}><MapPin className="h-3.5 w-3.5" aria-hidden />Place in a box…</Button>
          {resultTables.length ? <Button type="button" size="sm" variant="ghost" onClick={() => setPanel(panel === "result" ? null : "result")}><Table2 className="h-3.5 w-3.5" aria-hidden />Fill from a result table…</Button> : null}
          <a download href="/api/samples/template" className="focus-ring inline-flex h-8 items-center rounded-[var(--ln-radius-control-sm)] px-2.5 text-sm font-medium text-moss hover:bg-warm">Download the template</a>
        </div>
      </div>

      {panel === "generate" ? (
        <div className="flex flex-wrap items-end gap-3 rounded-[var(--ln-radius-panel)] border border-hairline bg-warm px-3 py-3 text-sm">
          <label><span className="mb-1 block text-xs text-muted">How many</span><input inputMode="numeric" value={generate.count} onChange={(event) => setGenerate({ ...generate, count: event.target.value })} className={cn(cellClass, "w-20")} /></label>
          <label><span className="mb-1 block text-xs text-muted">Name before the number</span><input value={generate.prefix} placeholder="P2026-" onChange={(event) => setGenerate({ ...generate, prefix: event.target.value })} className={cn(cellClass, "w-32")} /></label>
          <label><span className="mb-1 block text-xs text-muted">First number</span><input inputMode="numeric" value={generate.start} onChange={(event) => setGenerate({ ...generate, start: event.target.value })} className={cn(cellClass, "w-20")} /></label>
          <label><span className="mb-1 block text-xs text-muted">Digits</span><input inputMode="numeric" value={generate.width} onChange={(event) => setGenerate({ ...generate, width: event.target.value })} className={cn(cellClass, "w-16")} /></label>
          <label><span className="mb-1 block text-xs text-muted">After the number</span><input value={generate.suffix} placeholder="-T" onChange={(event) => setGenerate({ ...generate, suffix: event.target.value })} className={cn(cellClass, "w-24")} /></label>
          <span className="text-xs text-muted">{`${t("e.g.")}${colon}${generate.prefix}${String(Number(generate.start) || 1).padStart(Number(generate.width) || 0, "0")}${generate.suffix}`}</span>
          <Button type="button" size="sm" variant="primary" onClick={generateRows}>Add rows</Button>
          <p className="basis-full text-xs text-muted">Codes are given from the type’s prefix when saved (RNA-0001…); type your own in the Code column to keep them.</p>
        </div>
      ) : null}

      {panel === "paste" ? (
        <div className="space-y-2 rounded-[var(--ln-radius-panel)] border border-hairline bg-warm px-3 py-3 text-sm">
          {!imported ? <>
            <textarea aria-label="Pasted table" value={pasteText} onChange={(event) => setPasteText(event.target.value)} rows={5} placeholder={t("Copy cells from Excel with their header row and paste them here.")} className={cn(formInputClass, "w-full font-mono text-xs")} />
            <Button type="button" size="sm" variant="primary" disabled={!pasteText.trim()} onClick={() => readTable(pasteText)}>Read the table</Button>
          </> : <>
            <p className="text-xs text-muted">{t(`${imported.rows.length} rows read. Check which column each one fills.`)}</p>
            <div className="flex flex-wrap gap-2">
              {imported.headers.map((header, index) => (
                <label key={`${header}-${index}`} className="min-w-32 text-xs"><span className="mb-1 block truncate text-muted" title={header}>{header}</span>
                  <select value={imported.columns[index]} onChange={(event) => setImported({ ...imported, columns: imported.columns.map((column, at) => (at === index ? event.target.value : column)) })} className={cn(cellClass, "h-8")}>
                    <option value="">Skip</option>
                    {sampleColumns.map((column) => <option key={column.key} value={column.key}>{column.label}</option>)}
                    {fieldType?.fields.map((field) => <option key={field.key} value={`field:${field.key}`}>{field.label}</option>)}
                  </select>
                </label>
              ))}
            </div>
            <div className="flex flex-wrap gap-2">
              <Button type="button" size="sm" variant="primary" onClick={() => { append(sampleRowsFromCells(imported.rows, imported.columns, lookup)); setImported(null); setPasteText(""); setPanel(null); }}>Add these rows</Button>
              <Button type="button" size="sm" variant="ghost" onClick={() => { append(sampleRowsFromCells(imported.rows, imported.columns, lookup), true); setImported(null); setPasteText(""); setPanel(null); }}>Replace the table</Button>
              <Button type="button" size="sm" variant="ghost" onClick={() => setImported(null)}>Back</Button>
            </div>
          </>}
        </div>
      ) : null}

      {panel === "place" ? (
        <div className="flex flex-wrap items-end gap-3 rounded-[var(--ln-radius-panel)] border border-hairline bg-warm px-3 py-3 text-sm">
          <label><span className="mb-1 block text-xs text-muted">Box</span>
            <select value={place.locationId} onChange={(event) => setPlace({ ...place, locationId: event.target.value })} className={cn(cellClass, "h-8 w-72 max-w-full")}>
              {locations.map((location) => <option key={location.id} value={location.id}>{location.label}{location.geometry ? ` · ${location.geometry.rows}×${location.geometry.columns}` : ""}</option>)}
            </select>
          </label>
          <label><span className="mb-1 block text-xs text-muted">From position</span><input value={place.start} maxLength={4} onChange={(event) => setPlace({ ...place, start: event.target.value })} className={cn(cellClass, "w-20")} /></label>
          <label className="inline-flex h-8 items-center gap-2"><input type="checkbox" checked={place.onlyEmpty} onChange={(event) => setPlace({ ...place, onlyEmpty: event.target.checked })} />Only rows without a position</label>
          <Button type="button" size="sm" variant="primary" disabled={!place.locationId} onClick={placeRows}>Place them</Button>
          <p className="basis-full text-xs text-muted">Positions are filled row by row, skipping those already held. A box without rows and columns takes the samples without positions; set its size under Boxes.</p>
        </div>
      ) : null}

      {panel === "result" ? (
        <div className="flex flex-wrap items-end gap-3 rounded-[var(--ln-radius-panel)] border border-hairline bg-warm px-3 py-3 text-sm">
          <label><span className="mb-1 block text-xs text-muted">Result table</span>
            <select value={resultKey} onChange={(event) => setResultKey(event.target.value)} className={cn(cellClass, "h-8 w-80 max-w-full")}>
              {resultTables.map((table) => <option key={table.key} value={table.key}>{table.label} · {table.rows.length}</option>)}
            </select>
          </label>
          <Button type="button" size="sm" variant="primary" onClick={fillFromResult}>Fill in</Button>
          <p className="basis-full text-xs text-muted">Rows are matched by name to the table’s sample column (by order when it has none); concentration, volume, box, position and the type’s fields are filled in. The two records are kept separately afterwards.</p>
        </div>
      ) : null}

      {message ? <p role={message.tone === "error" ? "alert" : "status"} className={message.tone === "error" ? "text-sm text-error" : "text-sm text-moss"}>{message.text}</p> : null}

      <div className="relative w-full min-w-0 max-w-full overflow-x-auto editorial-scrollbar rounded-[var(--ln-radius-panel)] border border-hairline bg-surface [contain:inline-size]">
        <table className="ln-sample-entry min-w-[1400px] text-sm">
          <thead className="bg-warm text-left text-xs text-muted">
            <tr>
              <th className="w-10 px-2 py-2">#</th><th className="min-w-40 px-2 py-2">Name *</th><th className="min-w-32 px-2 py-2">Code</th><th className="min-w-32 px-2 py-2">Type</th>
              <th className="min-w-36 px-2 py-2">Origin</th><th className="min-w-32 px-2 py-2">Parent sample</th><th className="min-w-48 px-2 py-2">Box</th><th className="min-w-20 px-2 py-2">Position</th>
              <th className="min-w-24 px-2 py-2">Amount</th><th className="min-w-20 px-2 py-2">Unit</th><th className="min-w-24 px-2 py-2">Concentration</th><th className="min-w-24 px-2 py-2">Unit</th>
              <th className="min-w-32 px-2 py-2">Date</th><th className="min-w-24 px-2 py-2">BSL</th><th className="min-w-40 px-2 py-2">Notes</th>
              {fieldType?.fields.map((field) => <th key={field.key} className="min-w-28 px-2 py-2">{field.label}</th>)}
              <th className="w-10 px-2 py-2"><span className="sr-only">Remove</span></th>
            </tr>
          </thead>
          <tbody>
            {rows.map((row, index) => (
              <EntryRow key={row.key} row={row} index={index} problems={problems.get(index)} types={types} locations={locations} fieldType={fieldType} batchType={batchType} onChange={update} onRemove={remove} onPaste={pasteIntoCell} />
            ))}
          </tbody>
        </table>
      </div>

      <div className="flex flex-wrap items-center gap-2">
        <span className="text-sm text-muted"><span className="tabular-nums">{filledRows}</span> / {MAX_SAMPLE_BATCH} <span>rows</span></span>
        <Button type="button" variant="secondary" disabled={busy || !filledRows} onClick={() => void check()}>Check</Button>
        <Button type="button" variant="primary" disabled={busy || !filledRows} onClick={() => void save()}>{busy ? "Saving…" : experiment ? "Register outputs" : "Save samples"}</Button>
      </div>
    </div>
  );
}

const EntryRow = memo(function EntryRow({ row, index, problems, types, locations, fieldType, batchType, onChange, onRemove, onPaste }: {
  row: SampleEntryRow; index: number; problems?: string[]; types: SampleTypeRef[]; locations: Location[]; fieldType?: SampleTypeRef; batchType: string;
  onChange: (key: string, patch: Partial<SampleRowInput>) => void; onRemove: (key: string) => void;
  onPaste: (event: ClipboardEvent<HTMLInputElement | HTMLSelectElement>, rowKey: string, column: Column) => void;
}) {
  const text = (column: Exclude<Column, "typeId" | "locationId" | "biosafetyLevel">, extra?: { placeholder?: string; mono?: boolean }) => (
    <input aria-label={`${column} ${index + 1}`} value={row[column] ?? ""} placeholder={extra?.placeholder} onChange={(event) => onChange(row.key, { [column]: event.target.value })} onPaste={(event) => onPaste(event, row.key, column)} className={cn(cellClass, extra?.mono && "font-mono")} />
  );
  const unknownType = row.typeId?.startsWith("unknown:") ? row.typeId.slice(8) : null;
  const unknownBox = row.locationId?.startsWith("unknown:") ? row.locationId.slice(8) : null;
  const typeId = row.typeId || batchType;
  return <>
    <tr className={problems?.length ? "bg-error-surface/40 align-top" : "align-top"}>
      <td className="px-2 py-1.5 text-xs tabular-nums text-muted">{index + 1}</td>
      <td className="px-1 py-1">{text("name")}</td>
      <td className="px-1 py-1">{text("code", { placeholder: "auto", mono: true })}</td>
      <td className="px-1 py-1">
        <select aria-label={`type ${index + 1}`} value={unknownType ? row.typeId : typeId} onChange={(event) => onChange(row.key, { typeId: event.target.value })} onPaste={(event) => onPaste(event, row.key, "typeId")} className={cellClass}>
          {unknownType ? <option value={row.typeId}>{unknownType} ?</option> : null}
          {types.map((type) => <option key={type.id} value={type.id}>{type.label}</option>)}
        </select>
      </td>
      <td className="px-1 py-1">{text("origin")}</td>
      <td className="px-1 py-1">{text("parentCode", { mono: true })}</td>
      <td className="px-1 py-1">
        <select aria-label={`box ${index + 1}`} value={row.locationId ?? ""} onChange={(event) => onChange(row.key, { locationId: event.target.value || undefined })} onPaste={(event) => onPaste(event, row.key, "locationId")} className={cellClass}>
          <option value="">Not placed</option>
          {unknownBox ? <option value={row.locationId}>{unknownBox} ?</option> : null}
          {locations.map((location) => <option key={location.id} value={location.id}>{location.label}</option>)}
        </select>
      </td>
      <td className="px-1 py-1">{text("position", { placeholder: "A1", mono: true })}</td>
      <td className="px-1 py-1">{text("amount")}</td>
      <td className="px-1 py-1">{text("amountUnit", { placeholder: types.find((type) => type.id === typeId)?.amountUnit || "µL" })}</td>
      <td className="px-1 py-1">{text("concentration")}</td>
      <td className="px-1 py-1">{text("concentrationUnit", { placeholder: types.find((type) => type.id === typeId)?.concentrationUnit || "ng/µL" })}</td>
      <td className="px-1 py-1">{text("collectedAt", { placeholder: "2026-10-31" })}</td>
      <td className="px-1 py-1">
        <select aria-label={`biosafety ${index + 1}`} value={row.biosafetyLevel ?? ""} onChange={(event) => onChange(row.key, { biosafetyLevel: event.target.value || undefined })} className={cellClass}>
          <option value="">—</option>
          {biosafetyLevels.map((level) => <option key={level} value={level}>{level}</option>)}
        </select>
      </td>
      <td className="px-1 py-1">{text("notes")}</td>
      {fieldType?.fields.map((field) => (
        <td key={field.key} className="px-1 py-1">
          {field.kind === "choice" && field.options ? (
            <select aria-label={`${field.label} ${index + 1}`} value={row.fields?.[field.key] ?? ""} disabled={typeId !== fieldType.id} onChange={(event) => onChange(row.key, { fields: { ...row.fields, [field.key]: event.target.value } })} className={cellClass}>
              <option value="">—</option>
              {field.options.map((option) => <option key={option} value={option}>{option}</option>)}
            </select>
          ) : <input aria-label={`${field.label} ${index + 1}`} value={row.fields?.[field.key] ?? ""} disabled={typeId !== fieldType.id} inputMode={field.kind === "number" ? "decimal" : undefined} onChange={(event) => onChange(row.key, { fields: { ...row.fields, [field.key]: event.target.value } })} className={cellClass} />}
        </td>
      ))}
      <td className="px-1 py-1"><button type="button" aria-label={`Remove row ${index + 1}`} title="Remove row" onClick={() => onRemove(row.key)} className="focus-ring inline-flex h-8 w-8 items-center justify-center rounded-[var(--ln-radius-control-sm)] text-muted hover:bg-error-surface hover:text-error"><Trash2 className="h-3.5 w-3.5" aria-hidden /></button></td>
    </tr>
    {problems?.length ? <tr><td /><td colSpan={15 + (fieldType?.fields.length ?? 0)} className="px-2 pb-2 text-xs text-error">{problems.map((problem, at) => <span key={at} className="mr-2 inline-block">{problem}</span>)}</td></tr> : null}
  </>;
});
