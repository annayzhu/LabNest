const dynamicNouns: Record<string, string> = {
  Entry: "记录",
  Experiment: "实验",
  Result: "结果",
  Report: "报告",
  Protocol: "实验规程",
  "Research Plan": "研究方案",
  Project: "项目",
};

function translateDynamic(value: string) {
  let match = value.match(/^Edit (.+)$/);
  if (match) return `编辑 ${match[1]}`;
  match = value.match(/^New (Entry|Experiment|Result|Report|Protocol|Research Plan|Project)$/);
  if (match) return `新建${dynamicNouns[match[1]]}`;
  match = value.match(/^Filter by (.+)$/);
  if (match) return `按${zhUi[match[1]] ?? match[1]}筛选`;
  match = value.match(/^Updated (.+)$/);
  if (match) return `更新于 ${match[1]}`;
  match = value.match(/^(\d+) versions?$/);
  if (match) return `${match[1]} 个版本`;
  match = value.match(/^(\d+) primary runs?$/);
  if (match) return `${match[1]} 次主要实验`;
  match = value.match(/^(\d+) rows · (\d+) columns · (.+)$/);
  if (match) return `${match[1]} 行 · ${match[2]} 列 · ${zhUi[match[3]] ?? match[3]}`;
  match = value.match(/^Source: (.+)$/);
  if (match) return `来源：${match[1]}`;
  match = value.match(/^Protocol source: (.+)$/);
  if (match) return `实验规程来源：${match[1]}`;
  match = value.match(/^Linked plans: (.+)$/);
  if (match) return `关联方案：${match[1]}`;
  match = value.match(/^(\d+) stored$/);
  if (match) return `已存储 ${match[1]} 个文件`;
  return value;
}

export function translateUiText(input: string, locale: AppLocale) {
  if (locale === "en" || !input) return input;
  const leading = input.match(/^\s*/)?.[0] ?? "";
  const trailing = input.match(/\s*$/)?.[0] ?? "";
  const value = input.trim();
  if (!value) return input;
  const translated = zhUi[value] ?? translateDynamic(value);
  return translated === value ? input : `${leading}${translated}${trailing}`;
}
