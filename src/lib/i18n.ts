  match = value.match(/^All (.+)$/);
  if (match) return `全部${zhUi[match[1]] ?? match[1]}`;
  match = value.match(/^(Import|Export) (Projects|Research Plans|Protocols|Experiments|Results|Inventory|Reports|Sequences)$/);
