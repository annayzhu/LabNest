  if (match) return `${match[1]} 个已分配物品`;
  match = value.match(/^(\d+) movement references$/);
  if (match) return `${match[1]} 条流转引用`;
  match = value.match(/^(\d+) sample references$/);
  if (match) return `${match[1]} 条样本引用`;
  match = value.match(/^(\d+) child locations$/);
  if (match) return `${match[1]} 个子位置`;
  match = value.match(/^Under (.+)$/);
  if (match) return `位于 ${match[1]} 下`;
  match = value.match(/^Select record (.+)$/);
  if (match) return `选择记录 ${match[1]}`;
  match = value.match(/^Table row (\d+), column (\d+)$/);
  if (match) return `表格第 ${match[1]} 行，第 ${match[2]} 列`;
